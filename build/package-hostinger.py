#!/usr/bin/env python3
"""
Package the built site for upload to Hostinger.

Cloudflare Pages reads _headers and _redirects; Apache/LiteSpeed does not, and
needs an .htaccess instead. This produces a zip whose contents drop straight
into public_html.

    python3 build/build.py              # regenerate the site
    python3 build/package-hostinger.py  # wrap it for Hostinger
"""

import os
import shutil
import tempfile
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")
OUT = os.path.join(ROOT, "hostinger-upload.zip")

# Cloudflare-only control files; meaningless to Apache.
SKIP = {"_headers", "_redirects", ".DS_Store"}

HTACCESS = """# adityadave.in - generated by build/package-hostinger.py
# Replaces the WordPress .htaccess entirely.

DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Always serve over HTTPS.
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !https
  RewriteRule ^(.*)$ https://%{HTTP_HOST}/$1 [R=301,L]
</IfModule>

# Preserve inbound links to the old WordPress site.
RedirectMatch 301 ^/hello-world/?$        /essays/
RedirectMatch 301 ^/venture-capital/?$    /essays/
RedirectMatch 301 ^/__trashed/?$          /about/
RedirectMatch 301 ^/feed/?$               /feed.xml
RedirectMatch 301 ^/category(/.*)?$       /essays/
RedirectMatch 301 ^/author(/.*)?$         /about/

# WordPress admin paths no longer exist.
RedirectMatch 301 ^/wp-admin(/.*)?$       /
RedirectMatch 301 ^/wp-login\\.php$        /
RedirectMatch 301 ^/wp-json(/.*)?$        /

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/jpeg       "access plus 1 year"
  ExpiresByType image/png        "access plus 1 year"
  ExpiresByType image/svg+xml    "access plus 1 year"
  # Short, because CSS and JS are not content-hashed and design edits
  # should show up the same day rather than next week.
  ExpiresByType text/css         "access plus 1 hour"
  ExpiresByType application/javascript "access plus 1 hour"
  ExpiresByType text/html        "access plus 10 minutes"
</IfModule>

<IfModule mod_headers.c>
  Header set X-Content-Type-Options "nosniff"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
  Header set Permissions-Policy "geolocation=(), microphone=(), camera=()"
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript
  AddOutputFilterByType DEFLATE application/xml text/xml image/svg+xml
</IfModule>
"""


def main():
    if not os.path.isdir(SITE):
        raise SystemExit("site/ not found - run python3 build/build.py first")

    staged = tempfile.mkdtemp(prefix="hostinger-")
    try:
        count = 0
        for root, dirs, files in os.walk(SITE):
            dirs[:] = [d for d in dirs if d not in SKIP]
            for name in files:
                if name in SKIP:
                    continue
                src = os.path.join(root, name)
                rel = os.path.relpath(src, SITE)
                dst = os.path.join(staged, rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copy2(src, dst)
                count += 1

        with open(os.path.join(staged, ".htaccess"), "w", encoding="utf-8") as fh:
            fh.write(HTACCESS)
        count += 1

        if os.path.exists(OUT):
            os.remove(OUT)
        with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as zf:
            for root, _, files in os.walk(staged):
                for name in files:
                    path = os.path.join(root, name)
                    zf.write(path, os.path.relpath(path, staged))

        size = os.path.getsize(OUT) / 1024
        print("Packaged %d files -> %s (%.0f KB)" % (count, os.path.basename(OUT), size))
        print("\nUpload this zip into public_html on Hostinger and extract it there.")
    finally:
        shutil.rmtree(staged, ignore_errors=True)


if __name__ == "__main__":
    main()
